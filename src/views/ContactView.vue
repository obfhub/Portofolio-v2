import emailjs from '@emailjs/browser';

export default {
  name: 'ContactView',
  data() {
    return {
      form: {
        name: '',
        email: '',
        message: ''
      },
      isSubmitting: false,
      submitMessage: ''
    };
  },
  mounted() {
    // Initialize EmailJS with public key
    emailjs.init('YxTuQBSzMl6tQuD7K');
  },
  methods: {
    async submitForm() {
      try {
        this.isSubmitting = true;
        this.submitMessage = '';

        // Validate form
        if (!this.form.name || !this.form.email || !this.form.message) {
          this.submitMessage = 'Please fill in all fields.';
          this.isSubmitting = false;
          return;
        }

        // Send email using EmailJS send method
        const templateParams = {
          to_email: 'deminschiiarcadie@gmail.com',
          from_name: this.form.name,
          from_email: this.form.email,
          message: this.form.message
        };

        const response = await emailjs.send(
          'service_9j5psto',
          'QkXH2ucd5vOMUyrJqJknd',
          templateParams,
          'YxTuQBSzMl6tQuD7K'
        );

        if (response.status === 200) {
          this.submitMessage = 'Message sent successfully! I\'ll get back to you soon.';
          this.form = { name: '', email: '', message: '' };
          
          // Clear success message after 5 seconds
          setTimeout(() => {
            this.submitMessage = '';
          }, 5000);
        } else {
          this.submitMessage = 'Failed to send message. Please try again.';
        }
      } catch (error) {
        console.error('EmailJS Error:', error);
        this.submitMessage = 'Error sending message. Please try again or contact directly at deminschiiarcadie@gmail.com';
      } finally {
        this.isSubmitting = false;
      }
    }
  }
}
